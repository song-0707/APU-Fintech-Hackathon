def is_meeting_related(question: str) -> bool:
    """
    Check if a question is likely meeting-related.
    Uses keyword matching and contextual phrases.
    """
    question_lower = question.lower().strip()

    # SPECIAL CASE: Short questions (1-2 words)
    short_meeting_words = [
        'summary', 'summarize', 'overview', 'recap', 'highlights',
        'decisions', 'action', 'actions', 'tasks', 'task',
        'participants', 'speakers', 'attendees', 'people'
    ]
    if question_lower in short_meeting_words:
        return True

    # Check for meeting keywords
    for keyword in MEETING_KEYWORDS:
        if keyword.lower() in question_lower:
            return True

    # Check for meeting-related phrases
    for phrase in MEETING_PHRASES:
        if phrase.lower() in question_lower:
            return True

    # Check for natural language patterns
    question_starters = ['what', 'who', 'why', 'when', 'where', 'how', 'which', 'whom']
    words = question_lower.split()
    if words and words[0] in question_starters:
        if len(words) >= 3:
            return True

    return False

def ask_coco(question, max_snippets=5, retry_count=3):
    """
    Ask Coco a question about your meetings using Groq.
    Returns an answer with citations if the question is meeting-related.
    """

    # --- STEP 0: RELEVANCE PRE-CHECK ---
    if not is_meeting_related(question):
        return {
            "answer": "🤷 I'm Coco, your meeting intelligence assistant. I can only answer questions about your meetings, decisions, action items, and participants. For example, you can ask me:\n\n• 'What decisions were made?'\n• 'What did Samuel say about certificates?'\n• 'Who was assigned to the task?'\n• 'Summarize the meeting'\n\nI don't have information about general topics like weather, news, or non-meeting related questions.",
            "citations": [],  # ✅ Empty citations for non-meeting questions
            "has_answer": False,
            "not_meeting_related": True
        }

    # --- STEP 1: Semantic Search ---
    try:
        results = collection.query(
            query_texts=[question],
            n_results=max_snippets
        )
    except Exception as e:
        return {
            "answer": f"Error searching memory: {e}",
            "citations": [],  # ✅ Empty citations on error
            "has_answer": False,
            "not_meeting_related": False
        }

    # --- STEP 2: Build Context ---
    context_lines = []
    citations = []

    if results['documents'] and results['documents'][0]:
        for i, doc in enumerate(results['documents'][0]):
            metadata = results['metadatas'][0][i] if results['metadatas'] else {}
            timestamp = metadata.get('timestamp', 'Unknown')
            speaker = metadata.get('speaker', 'Unknown')
            context_lines.append(f"[{timestamp}] {speaker}: {doc}")
            citations.append({
                "timestamp": timestamp,
                "speaker": speaker,
                "source": metadata.get('source', 'Meeting')
            })
    else:
        return {
            "answer": "🤷 I couldn't find any relevant information about that in your meeting records. Try asking about specific decisions, speakers, or topics discussed in your meetings.",
            "citations": [],  # ✅ Empty citations when no data found
            "has_answer": False,
            "not_meeting_related": False
        }

    context = "\n".join(context_lines)

    # --- STEP 3: Build Prompt ---
    prompt = f"""
You are Coco, the AI assistant for Corporate Brain. You answer questions based ONLY on the meeting transcripts provided below.

**Context (from processed meetings):**
{context}

**Question:** {question}

**Instructions:**
1. Answer the question using ONLY the information in the context above.
2. If the context doesn't contain the answer, say: "I don't have information about that in my meeting records."
3. If you use specific information, cite the source using the timestamp and speaker.
4. Be concise but informative (2-3 sentences maximum).
5. Never mention that you're an AI or that you're using a transcript.

**Answer:**
"""

    # --- STEP 4: Generate Answer with Groq (with retry) ---
    for attempt in range(retry_count):
        try:
            response = client.chat.completions.create(
                model="qwen/qwen3.6-27b",
                messages=[
                    {"role": "user", "content": prompt}
                ],
                temperature=0.3,
                max_tokens=500
            )

            answer = response.choices[0].message.content.strip()
            if answer.startswith("Answer:"):
                answer = answer[7:].strip()

            print(f"✅ Answer generated successfully using Groq!")

            # --- Post-check: Check if the answer actually contains useful info ---
            if len(answer) < 10 or "don't have information" in answer.lower():
                return {
                    "answer": "🤷 I don't have information about that in my meeting records. Try asking about specific decisions, speakers, or topics discussed in your meetings.",
                    "citations": [],  # ✅ Empty citations when no answer
                    "has_answer": False,
                    "not_meeting_related": False
                }

            # ✅ Only return citations if we have a valid answer
            return {
                "answer": answer,
                "citations": citations,  # ✅ Citations only for valid answers
                "has_answer": True,
                "context": context_lines,
                "not_meeting_related": False
            }

        except Exception as e:
            error_msg = str(e)
            if "429" in error_msg or "rate limit" in error_msg.lower():
                wait_time = (attempt + 1) * 3
                print(f"⚠️ Rate limited. Retrying in {wait_time} seconds... (Attempt {attempt+1}/{retry_count})")
                time.sleep(wait_time)
            else:
                print(f"❌ Groq error: {error_msg}")
                return {
                    "answer": f"Error: {error_msg}",
                    "citations": [],  # ✅ Empty citations on error
                    "has_answer": False,
                    "not_meeting_related": False
                }

    return {
        "answer": "Sorry, I'm having trouble connecting to my brain right now. Please try again in a moment.",
        "citations": [],  # ✅ Empty citations on timeout
        "has_answer": False,
        "not_meeting_related": False
    }

