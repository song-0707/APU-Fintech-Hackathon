# --- Submit handler ---
def on_submit(b):
    global chat_history
    question = question_input.value.strip()

    if not question:
        with output_area:
            clear_output()
            print("⚠️ Please enter a question.")
        return

    # Clear input
    question_input.value = ''

    with output_area:
        clear_output(wait=True)

        # Show chat history
        for entry in chat_history:
            print(f"🧑 **You:** {entry['question']}")
            print(f"🧠 **Coco:** {entry['answer']}\n")
            # ✅ Only show citations if they exist
            if entry.get('citations') and len(entry.get('citations', [])) > 0:
                for cite in entry['citations']:
                    print(f"   📎 Source: {cite['source']} at {cite['timestamp']} ({cite['speaker']})")
            print("-" * 50)

        # Get response
        print(f"🧑 **You:** {question}")
        print("🧠 **Coco:** Thinking...")

        # Call ask_coco with debug output
        try:
            result = ask_coco(question)
            answer = result.get("answer", "No response")
            citations = result.get("citations", [])
            not_meeting = result.get("not_meeting_related", False)
        except Exception as e:
            answer = f"❌ Error: {e}"
            citations = []
            not_meeting = False
            print(f"❌ Error in ask_coco: {e}")

        # Display answer
        clear_output(wait=True)

        # Add to chat history
        chat_history.append({
            "question": question,
            "answer": answer,
            "citations": citations,
            "not_meeting": not_meeting
        })

        # Display all chat messages
        for entry in chat_history:
            # Show a special icon for non-meeting questions
            if entry.get('not_meeting', False):
                print(f"🧑 **You:** {entry['question']}")
